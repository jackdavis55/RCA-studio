import {expect,test} from '@playwright/test'
import seed from '../cases.json'

for(const width of [1440,1024,390]) test(`renders every view at ${width}px`,async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
  await page.setViewportSize({width,height:900})
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Initiating triggers'})).toBeVisible()
  await expect(page.getByRole('button',{name:/Environmental Ruled out/})).toBeVisible()
  await expect(page.locator('.trigger-card')).toHaveCount(8)
  for(const data of seed.cases){
    await page.getByLabel('Investigation',{exact:true}).selectOption(data.id)
    await expect(page.getByRole('heading',{name:data.title,exact:true})).toBeVisible()
  }
  await page.getByLabel('Investigation',{exact:true}).selectOption('RCA-001')
  const views=page.getByRole('navigation',{name:'Visualisation modes'})
  await page.getByRole('button',{name:'Open full timeline'}).click()
  for (const title of ['Maintenance deferral recorded','Standby isolation arrangement checked','Utility voltage advisory received','Alarm display refresh delayed']) {
    await expect(page.locator('.time-row').getByRole('button',{name:new RegExp(title)})).toBeVisible()
  }
  await expect(page.getByRole('heading',{name:'Undated events'})).toBeVisible()
  await expect(page.locator('.duration')).toHaveCount(1)
  await views.getByRole('button',{name:'Swimlanes'}).click()
  await expect(page.locator('.lane-link').first()).toBeAttached()
  await page.getByRole('button',{name:'Reset playback'}).click()
  await expect(page.getByRole('slider',{name:'Playback position'})).toHaveValue('0')
  await expect(page.getByRole('button',{name:/Earlier control weakness/})).toBeVisible()
  await page.getByRole('button',{name:'Play playback'}).click()
  await expect(page.getByRole('slider',{name:'Playback position'})).not.toHaveValue('0')
  await page.getByRole('button',{name:'Pause playback'}).click()
  await views.getByRole('button',{name:'Causal Map'}).click()
  await expect(page.locator('.react-flow__node')).not.toHaveCount(0)
  await expect(page.getByText('Arranging graph…')).toHaveCount(0)
  await expect(page.locator('.graph-canvas').getByText('Lightning interference',{exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Filters',exact:true}).click()
  await page.getByRole('checkbox',{name:'Ruled-out relationships'}).check()
  await expect(page.locator('.graph-canvas').getByText('Lightning interference',{exact:true})).toBeVisible()
  await views.getByRole('button',{name:'Bow-tie'}).click()
  await expect(page.getByRole('button',{name:/Failed/}).first()).toBeVisible()
  await expect(page.getByText('Prevented',{exact:true})).toBeVisible()
  await views.getByRole('button',{name:'Fault Tree'}).click()
  await expect(page.getByText('All inputs required',{exact:true})).toBeVisible()
  if(width===390) await page.getByRole('button',{name:'Toggle navigation'}).click()
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Findings & Actions'}).click()
  await expect(page.getByRole('columnheader',{name:'Corrective action'})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  expect(errors).toEqual([])
})

test('edits, filters, reloads, undoes, exports, imports and resets',async({page})=>{
  await page.goto('/')
  const title='Revised normal operation'
  await page.locator('.sequence').getByRole('button',{name:/Normal operation/}).click()
  await page.getByRole('button',{name:'Edit event',exact:true}).click()
  await page.getByLabel('Title',{exact:true}).fill(title)
  await page.getByRole('button',{name:'Save changes'}).click()
  await expect(page.getByRole('heading',{name:title})).toBeVisible()
  await page.getByRole('button',{name:'Undo change'}).click()
  await expect(page.locator('.sequence').getByRole('button',{name:/Normal operation/})).toBeVisible()
  await page.getByRole('button',{name:'Redo change'}).click()
  await expect(page.locator('.sequence').getByRole('button',{name:new RegExp(title)})).toBeVisible()
  await page.getByLabel('Search events and evidence').fill('nonexistent string')
  await expect(page.getByText('This selection is hidden by the current filters.')).toBeVisible()
  await page.getByLabel('Search events and evidence').clear()
  await page.reload()
  await expect(page.locator('.sequence').getByRole('button',{name:new RegExp(title)})).toBeVisible()
  await page.getByLabel('Export options').click()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'Export current case'}).click()
  const exported=await download
  expect(exported.suggestedFilename()).toBe('RCA-001.json')
  await page.getByRole('button',{name:'Import',exact:true}).click()
  await page.getByLabel('Investigation file').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{"schemaVersion":2,"cases":[]}')})
  await page.getByRole('radio',{name:'Replace the entire collection'}).check()
  await page.getByRole('button',{name:'Import cases'}).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('schemaVersion')
  await page.getByLabel('Investigation file').setInputFiles((await exported.path())!)
  await page.getByRole('button',{name:'Import cases'}).click()
  await expect(page.getByLabel('Investigation',{exact:true}).locator('option')).toHaveCount(1)
  await expect(page.locator('.sequence').getByRole('button',{name:new RegExp(title)})).toBeVisible()
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Reset to seed'}).click()
  await expect(page.getByLabel('Investigation',{exact:true}).locator('option')).toHaveCount(8)
  await expect(page.locator('.sequence').getByRole('button',{name:/Normal operation/})).toBeVisible()
})

test('blocks deletion of a referenced event and adds a condition through the graph palette',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Causal Map'}).click()
  await page.getByRole('button',{name:'Edit graph'}).click()
  await page.getByRole('button',{name:'Condition',exact:true}).click()
  await page.getByLabel('Title',{exact:true}).fill('New latent condition')
  await page.getByRole('button',{name:'Save changes'}).click()
  await expect(page.getByRole('heading',{name:'New latent condition'})).toBeVisible()
  await page.getByRole('button',{name:'Overview',exact:true}).click()
  await page.locator('.sequence').getByRole('button',{name:/Plant shutdown/}).click()
  const dialogs:string[]=[]
  page.on('dialog',async dialog=>{dialogs.push(dialog.message());await dialog.accept()})
  await page.getByRole('button',{name:'Delete selected record'}).click()
  await expect.poll(()=>dialogs.length).toBe(2)
  expect(dialogs[1]).toContain('top event')
  await expect(page.locator('.sequence').getByRole('button',{name:/Plant shutdown/})).toBeVisible()
})

test('adds a causal relationship and rejects a cycle without losing the draft',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Causal Map'}).click()
  await page.getByRole('button',{name:'Edit graph'}).click()
  const relationship=page.getByRole('button',{name:'Relationship',exact:true})
  await relationship.click()
  let editor=page.getByRole('dialog')
  await editor.locator('select[name=source]').selectOption('normal')
  await editor.locator('select[name=target]').selectOption('trigger')
  await editor.getByLabel('Rationale',{exact:true}).fill('A test relationship')
  await editor.getByRole('button',{name:'Save changes'}).click()
  await expect(page.getByRole('heading',{name:'Normal operation → Bypass step omitted'})).toBeVisible()
  await relationship.click()
  editor=page.getByRole('dialog')
  await editor.locator('select[name=source]').selectOption('top')
  await editor.locator('select[name=target]').selectOption('latent')
  await editor.getByLabel('Rationale',{exact:true}).fill('Cycle test')
  await editor.getByRole('button',{name:'Save changes'}).click()
  await expect(editor.getByRole('alert')).toContainText('cycle')
  await expect(editor.getByLabel('Rationale',{exact:true})).toHaveValue('Cycle test')
})
